import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Writes src/html/legacy-entities.ts from the WHATWG entity list
 * (https://html.spec.whatwg.org/entities.json, passed as the first argument).
 * HTML also reads the legacy names without a `;`. Each one decodes like its
 * `;` twin in src/markdown/engine/entities.ts, so only the names are written.
 */
const [source] = process.argv.slice(2);

if (source === undefined) {
  throw new Error('usage: node scripts/generate-html-legacy-entities.mjs <entities.json>');
}

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entities = JSON.parse(readFileSync(source, 'utf8'));
const names = Object.keys(entities);
const legacy = names.filter((name) => !name.endsWith(';')).map((name) => name.slice(1)).sort();

legacy.forEach((name) => {
  const twin = entities[`&${name};`];

  if (twin === undefined || twin.characters !== entities[`&${name}`].characters) {
    throw new Error(`&${name} has no matching &${name}; twin`);
  }
});

const packed = readFileSync(path.join(root, 'src/markdown/engine/entities.ts'), 'utf8').match(/PACKED_ENTITIES = (".*");/);
const semicolonNames = names.filter((name) => name.endsWith(';')).map((name) => `${name.slice(1, -1)} ${entities[name].characters}`).sort();

if (packed === null || JSON.parse(packed[1]) !== semicolonNames.join('~')) {
  throw new Error('src/markdown/engine/entities.ts differs from this list; run scripts/generate-markdown-entities.mjs first');
}

const header = '// Generated by scripts/generate-html-legacy-entities.mjs from the WHATWG entity list. Do not edit.';
const doc = '/** Names that HTML also reads without a trailing `;`, joined by spaces. */';

writeFileSync(
  path.join(root, 'src/html/legacy-entities.ts'),
  `${header}\n\n${doc}\nexport const LEGACY_ENTITIES = ${JSON.stringify(legacy.join(' '))};\n`
);
console.log(`wrote ${legacy.length} legacy entities`);
