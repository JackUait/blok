function buildAny() {
  const cases = ANY_CASES.map(({ name, value }) => {
    const bytes = writeAnyBytes(buildValue(value));

    return { name, value, tag: bytes[0], bytes: b64(bytes) };
  });

  // A Date is written as an object with zero keys, so the value cannot be
  // reproduced from the bytes: decode-only.
  const dateBytes = writeAnyBytes(new Date(0));

  cases.push({
    name: 'date',
    value: {},
    tag: dateBytes[0],
    bytes: b64(dateBytes),
    decodeOnly: true,
    note: 'written as new Date(0); lib0 writeAny emits tag 118 with zero keys, so it decodes to {}',
  });

  return {
    $comment: DO_NOT_EDIT,
    $description:
      'lib0 writeAny goldens. `value` is the DECODED value in the Locked-Decision-10 sentinel ' +
      'vocabulary; `tag` is the first byte. Every case must decode from `bytes` to `value`, and ' +
      'every case without `decodeOnly` must also encode from `value` back to `bytes`.',
    cases,
  };
}

const VARUINT_VALUES = [0, 1, 63, 64, 127, 128, 255, 16383, 16384, 2097151, 2097152, 1000, 1001, 1002, 2147483647, 2147483648, 4294967295, 4294967296, 9007199254740991];
const VARINT_VALUES = [0, 1, -1, 63, -63, 64, -64, 127, -127, 128, -128, 8191, -8191, 8192, -8192, 2147483647, -2147483647, 2147483648, -2147483648, 9007199254740991, -9007199254740991];

function buildVarint() {
  const encode = (write, value) => {
    const encoder = encoding.createEncoder();

    write(encoder, value);

    return b64(encoding.toUint8Array(encoder));
  };

  const varint = VARINT_VALUES.map((value) => ({ value, bytes: encode(encoding.writeVarInt, value) }));

  // -0 has its own encoding (the sign bit set on a zero payload) and cannot be
  // spelled in JSON, so it carries the sentinel instead of a numeric `value`.
  varint.push({ value: { $num: '-0' }, bytes: encode(encoding.writeVarInt, -0) });

  return {
    $comment: DO_NOT_EDIT,
    $description:
      'lib0 varuint (LEB128, 53-bit safe) and varint (sign bit 0x40 in the first byte) goldens. ' +
      'A `value` object is a sentinel, never a number.',
    varuint: VARUINT_VALUES.map((value) => ({ value, bytes: encode(encoding.writeVarUint, value) })),
    varint,
  };
}

