import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Writes src/html/entities.ts from the WHATWG entity list
 * (https://html.spec.whatwg.org/entities.json, passed as the first argument):
 * every name ending in `;`, plus the legacy names HTML also reads without one.
 * Each legacy name decodes like its `;` twin, so only the names are written.
 *
 * The named table repeats src/markdown/engine/entities.ts on purpose. A module
 * shared by the Markdown engine and src/html lands in a chunk the editor loads
 * up front, so sharing it would make every editor page load the table.
 */
const [source] = process.argv.slice(2);

if (source === undefined) {
  throw new Error('usage: node scripts/generate-html-entities.mjs <entities.json>');
}

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entities = JSON.parse(readFileSync(source, 'utf8'));
const names = Object.keys(entities);
const legacy = names.filter((name) => !name.endsWith(';')).map((name) => name.slice(1)).sort();

legacy.forEach((name) => {
  const twin = entities[`&${name};`];

  if (twin === undefined || twin.characters !== entities[`&${name}`].characters) {
    throw new Error(`&${name} has no matching &${name}; twin`);
  }
});

const packed = readFileSync(path.join(root, 'src/markdown/engine/entities.ts'), 'utf8').match(/PACKED_ENTITIES = (".*");/);
const semicolonNames = names.filter((name) => name.endsWith(';')).map((name) => `${name.slice(1, -1)} ${entities[name].characters}`).sort();

if (packed === null || JSON.parse(packed[1]) !== semicolonNames.join('~')) {
  throw new Error('src/markdown/engine/entities.ts differs from this list; run scripts/generate-markdown-entities.mjs first');
}

const header = '// Generated by scripts/generate-html-entities.mjs from the WHATWG entity list. Do not edit.';
const namedDoc = '/** `name characters` pairs for every name that ends in `;` (without it), joined by `~`. */';
const legacyDoc = '/** Names that HTML also reads without a trailing `;`, joined by spaces. */';

writeFileSync(
  path.join(root, 'src/html/entities.ts'),
  `${header}\n\n${namedDoc}\nexport const NAMED_ENTITIES = ${packed[1]};\n\n${legacyDoc}\nexport const LEGACY_ENTITIES = ${JSON.stringify(legacy.join(' '))};\n`
);
console.log(`wrote ${semicolonNames.length} named and ${legacy.length} legacy entities`);
