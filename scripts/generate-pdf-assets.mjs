#!/usr/bin/env node
/**
 * Writes src/tools/file/pdf/assets/: one module per pdf.js data file, each
 * exporting the file as a base64 string, plus index.ts with a lazy loader per
 * file. The PDF preview hands them to pdf.js through BinaryDataFactory, so a
 * host does not have to serve pdf.js's folders.
 *
 * Run: node scripts/generate-pdf-assets.mjs (after bumping pdfjs-dist).
 * test/unit/tools/file/pdf/pdf-assets.test.ts fails while the output is stale.
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pdfjs = path.join(root, 'node_modules', 'pdfjs-dist');
const out = path.join(root, 'src', 'tools', 'file', 'pdf', 'assets');

// With useSystemFonts on, pdf.js only fetches the Symbol and ZapfDingbats
// fonts. Both are Foxit's (BSD). qcms (ICC) and quickjs are left out: pdf.js
// reads them by url only.
const GROUPS = [
  { kind: 'cMapUrl', from: 'cmaps', dir: 'cmaps', pick: (name) => name.endsWith('.bcmap') },
  { kind: 'standardFontDataUrl', from: 'standard_fonts', dir: 'fonts', pick: (name) => ['FoxitDingbats.pfb', 'FoxitSymbol.pfb'].includes(name) },
  { kind: 'wasmUrl', from: 'wasm', dir: 'wasm', pick: (name) => ['jbig2.wasm', 'openjpeg.wasm'].includes(name) },
];

const HEADER = '// Generated by scripts/generate-pdf-assets.mjs from pdfjs-dist. Do not edit.\n';
const version = JSON.parse(fs.readFileSync(path.join(pdfjs, 'package.json'), 'utf8')).version;

fs.rmSync(out, { recursive: true, force: true });

const index = [HEADER, `// pdfjs-dist ${version}\n`, '\nexport const PDF_ASSET_FILES = {\n'];

for (const group of GROUPS) {
  fs.mkdirSync(path.join(out, group.dir), { recursive: true });
  index.push(`  ${group.kind}: {\n`);
  const names = fs.readdirSync(path.join(pdfjs, group.from)).filter(group.pick).sort();
  for (const name of names) {
    const module = name.replace(/\.[^.]+$/, '');
    // 76-char lines (MIME): atob skips the newlines, and source scanners with
    // greedy regexes go quadratic on one megabyte-long token.
    const base64 = fs.readFileSync(path.join(pdfjs, group.from, name)).toString('base64').match(/.{1,76}/g).join('\n');
    fs.writeFileSync(path.join(out, group.dir, `${module}.ts`), `${HEADER}export default \`\n${base64}\n\`;\n`);
    index.push(`    '${name}': async (): Promise<string> => (await import('./${group.dir}/${module}')).default,\n`);
  }
  index.push('  },\n');
}

index.push('} as const;\n');
fs.writeFileSync(path.join(out, 'index.ts'), index.join(''));
console.log(`✓ pdf.js assets written to ${path.relative(root, out)}`);
