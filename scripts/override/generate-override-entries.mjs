import { existsSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { init, parse } from 'es-module-lexer';

const __dirname = dirname(fileURLToPath(import.meta.url));

export const WRAPPER_MARKER = '/* @blok-override-wrapper v1 */';

const GENERATED_NOTE = '/* generated by scripts/override/generate-override-entries.mjs — do not edit */';

export const ENTRIES = [
  { file: 'blok', key: 'core', formats: ['mjs', 'cjs'] },
  { file: 'tools', key: 'tools', formats: ['mjs', 'cjs'] },
  { file: 'full', key: 'full', formats: ['mjs', 'cjs'] },
  { file: 'markdown', key: 'markdown', formats: ['mjs', 'cjs'] },
  { file: 'view', key: 'view', formats: ['mjs', 'cjs'] },
  { file: 'migrate', key: 'migrate', formats: ['mjs', 'cjs'] },
  { file: 'adapters', key: 'adapters', formats: ['mjs', 'cjs'] },
  { file: 'icons', key: 'icons', formats: ['mjs', 'cjs'] },
  { file: 'locales', key: 'locales', formats: ['mjs'] },
];

const RUNTIME_SOURCE = resolve(__dirname, 'override-runtime.mjs');

const isWrapped = (path) => existsSync(path) && readFileSync(path, 'utf8').startsWith(WRAPPER_MARKER);

/** Export names come from lexing the ESM impl — the built file is the truth. */
const exportNamesOf = (implMjsPath) => {
  const [, exports] = parse(readFileSync(implMjsPath, 'utf8'));
  return exports.map((e) => e.n).sort();
};

const esmWrapper = (entry, names) => {
  const named = names.filter((n) => n !== 'default');
  const hasDefault = names.includes('default');
  const lines = [
    WRAPPER_MARKER,
    GENERATED_NOTE,
    `import * as impl from './${entry.file}-impl.mjs';`,
    `import { resolveOverrideEntry } from './override-runtime.mjs';`,
    `const o = resolveOverrideEntry('${entry.key}', ${JSON.stringify(names)});`,
    `const pick = (n, fb) => (o ? o[n] : fb);`,
    ...named.map((n) => `export const ${n} = /* @__PURE__ */ pick('${n}', impl.${n});`),
  ];
  if (hasDefault) {
    lines.push(`const _default = /* @__PURE__ */ pick('default', impl.default);`, 'export default _default;');
  }
  return `${lines.join('\n')}\n`;
};

const cjsWrapper = (entry, names) => `${WRAPPER_MARKER}
${GENERATED_NOTE}
'use strict';
const impl = require('./${entry.file}-impl.cjs');
const { resolveOverrideEntry } = require('./override-runtime.cjs');
const NAMES = ${JSON.stringify(names)};
const o = resolveOverrideEntry('${entry.key}', NAMES);
if (o) {
  const out = { __esModule: true };
  for (const n of NAMES) {
    out[n] = o[n];
  }
  module.exports = out;
} else {
  module.exports = impl;
}
`;

const copyRuntime = (distDir) => {
  const source = readFileSync(RUNTIME_SOURCE, 'utf8');
  writeFileSync(join(distDir, 'override-runtime.mjs'), source);
  const cjs = source
    .replace('export const PROTOCOL', 'const PROTOCOL')
    .replace('export function resolveOverrideEntry', 'function resolveOverrideEntry');
  writeFileSync(join(distDir, 'override-runtime.cjs'), `${cjs}\nmodule.exports = { PROTOCOL, resolveOverrideEntry };\n`);
};

export async function wrapDist(distDir) {
  await init;
  copyRuntime(distDir);
  for (const entry of ENTRIES) {
    for (const ext of entry.formats) {
      const entryPath = join(distDir, `${entry.file}.${ext}`);
      const implPath = join(distDir, `${entry.file}-impl.${ext}`);
      if (isWrapped(entryPath)) {
        continue;
      }
      if (!existsSync(entryPath)) {
        throw new Error(`cannot wrap ${entry.file}.${ext}: file is missing from ${distDir}`);
      }
      renameSync(entryPath, implPath);
      // Names always come from the ESM impl — the lexer cannot parse CJS, and
      // both formats are emitted from the same module graph.
      const names = exportNamesOf(join(distDir, `${entry.file}-impl.mjs`));
      writeFileSync(entryPath, ext === 'mjs' ? esmWrapper(entry, names) : cjsWrapper(entry, names));
    }
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const distDir = resolve(__dirname, '../../dist');
  await wrapDist(distDir);
  console.log('override wrappers generated in dist/');
}
