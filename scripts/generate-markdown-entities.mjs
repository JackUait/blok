import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Writes src/markdown/engine/entities.ts from the WHATWG entity list
 * (https://html.spec.whatwg.org/entities.json, passed as the first argument).
 * CommonMark reads only references that end in `;`, so the legacy forms
 * without one are left out. The list is frozen by the HTML spec.
 */
const [source] = process.argv.slice(2);

if (source === undefined) {
  throw new Error('usage: node scripts/generate-markdown-entities.mjs <entities.json>');
}

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entries = Object.entries(JSON.parse(readFileSync(source, 'utf8')))
  .filter(([name]) => name.endsWith(';'))
  .map(([name, { characters }]) => {
    if (/[ ~]/.test(characters)) {
      throw new Error(`${name} holds a separator`);
    }

    return `${name.slice(1, -1)} ${characters}`;
  })
  .sort();

const header = '// Generated by scripts/generate-markdown-entities.mjs from the WHATWG entity list. Do not edit.';
const doc = '/** `name characters` pairs joined by `~`. No value holds a space or a `~`. */';

writeFileSync(
  path.join(root, 'src/markdown/engine/entities.ts'),
  `${header}\n\n${doc}\nexport const PACKED_ENTITIES = ${JSON.stringify(entries.join('~'))};\n`
);
console.log(`wrote ${entries.length} entities`);
