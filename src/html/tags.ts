const TAG_NAME_TO_ID = new Map<string, TAG_ID>(TAG_NAMES.map((name, index): [string, TAG_ID] => [name, index + 1]));

export const getTagID = (tagName: string): TAG_ID => TAG_NAME_TO_ID.get(tagName) ?? TAG_ID.UNKNOWN;

