use std::fmt::Write as _;
use std::path::Path;
use std::time::Instant;

use blok_collab_collabtest as collabtest;
use blok_jsjson::{Str, Value};
use blok_yjs_yjstest::field;

use crate::graphemes::text_element_starts;
use crate::textdiff::{TextEdit, atomize, diff};

struct TextDiffCase {
    before: Str,
    after: Str,
    markup: bool,
    atoms: Vec<Str>,
    elements: Vec<usize>,
    edits: Vec<TextEdit>,
}

fn get<'a>(value: &'a Value, key: &str) -> &'a Value {
    field(value, key).unwrap_or_else(|| panic!("no {key}"))
}

fn string(value: &Value) -> Str {
    match value {
        Value::String(s) => s.clone(),
        other => panic!("not a string: {other:?}"),
    }
}

fn array(value: &Value) -> &[Value] {
    match value {
        Value::Array(items) => items,
        other => panic!("not an array: {other:?}"),
    }
}

fn number(value: &Value) -> usize {
    match value {
        Value::Number(n) => *n as usize,
        other => panic!("not a number: {other:?}"),
    }
}

fn load_text_diff_cases() -> Vec<TextDiffCase> {
    // jsjson keeps the lone surrogates a UTF-8 decoder would replace.
    let root = collabtest::read("text-diff/cases.json");
    let cases: Vec<TextDiffCase> = array(get(&root, "cases"))
        .iter()
        .map(|raw| TextDiffCase {
            before: string(get(raw, "before")),
            after: string(get(raw, "after")),
            markup: matches!(get(raw, "markup"), Value::Bool(true)),
            atoms: array(get(raw, "atoms")).iter().map(string).collect(),
            elements: array(get(raw, "elements")).iter().map(number).collect(),
            edits: array(get(raw, "edits"))
                .iter()
                .map(|edit| {
                    let parts = array(edit);
                    TextEdit {
                        index: number(&parts[0]),
                        remove: number(&parts[1]),
                        insert: string(&parts[2]),
                    }
                })
                .collect(),
        })
        .collect();
    assert!(cases.len() >= 300, "only {} cases", cases.len());
    cases
}

#[test]
fn splits_text_elements_like_string_info() {
    for (i, c) in load_text_diff_cases().iter().enumerate() {
        let got = text_element_starts(&c.before);
        assert_eq!(got, c.elements, "case {i} {:?}", c.before);
    }
}

#[test]
fn atomizes_like_c_sharp() {
    for (i, c) in load_text_diff_cases().iter().enumerate() {
        let got = atomize(&c.before, c.markup);
        assert!(
            got == c.atoms,
            "case {i} {:?} markup={}:\n got {} atoms\nwant {}",
            c.before,
            c.markup,
            got.len(),
            c.atoms.len()
        );
    }
}

#[test]
fn diffs_like_c_sharp() {
    for (i, c) in load_text_diff_cases().iter().enumerate() {
        let got = diff(&c.before, &c.after, c.markup);
        assert_eq!(got, c.edits, "case {i} {:?} -> {:?}", c.before, c.after);
    }
}

const GRAPHEME_KINDS: [(&str, &str); 14] = [
    ("Control", "Control"),
    ("CR", "Cr"),
    ("LF", "Lf"),
    ("Extend", "Extend"),
    ("ZWJ", "Zwj"),
    ("Regional_Indicator", "RegionalIndicator"),
    ("Prepend", "Prepend"),
    ("SpacingMark", "SpacingMark"),
    ("L", "L"),
    ("V", "V"),
    ("T", "T"),
    ("LV", "Lv"),
    ("LVT", "Lvt"),
    ("Extended_Pictograph", "ExtendedPictograph"),
];

// The Rust table is generated from the C# capture; BLOK_WRITE_RUST_TABLES=1 rewrites it.
#[test]
fn the_grapheme_table_is_the_capture() {
    let capture = collabtest::read("text-diff/grapheme-break.json");
    let mut source = String::new();
    source.push_str("// Code generated by the_grapheme_table_is_the_capture from\n");
    source.push_str("// fixtures/text-diff/grapheme-break.json. DO NOT EDIT.\n\n");
    source.push_str("use crate::graphemes::GraphemeBreak as G;\n\n");
    source.push_str("/// .NET's Grapheme_Cluster_Break table; code points not listed are Other.\n");
    source.push_str("#[rustfmt::skip]\n");
    source.push_str("pub(crate) static GRAPHEME_RANGES: &[(u32, u32, G)] = &[\n");
    for range in array(get(&capture, "ranges")) {
        let parts = array(range);
        let name = string(&parts[2]).to_string();
        let kind = GRAPHEME_KINDS
            .iter()
            .find(|(capture, _)| *capture == name)
            .unwrap_or_else(|| panic!("unknown type {name}"))
            .1;
        writeln!(
            source,
            "    (0x{:X}, 0x{:X}, G::{kind}),",
            number(&parts[0]),
            number(&parts[1])
        )
        .unwrap();
    }
    source.push_str("];\n");
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("src/graphemes_table.rs");
    if std::env::var("BLOK_WRITE_RUST_TABLES").as_deref() == Ok("1") {
        std::fs::write(&path, &source).unwrap();
    }
    let committed = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        committed == source,
        "{} is stale; rerun with BLOK_WRITE_RUST_TABLES=1",
        path.display()
    );
}

// One long conjunct is one growing character. Joining each consonant must not
// walk back to the character's start, or one edit costs seconds of CPU.
#[test]
fn a_long_conjunct_run_diffs_in_linear_time() {
    let run = Str::from("क्".repeat(32000));
    let started = Instant::now();
    let mut with_ka = run.clone();
    with_ka.push(0x0915);
    let atoms = atomize(&with_ka, true);
    let mut with_x = run.clone();
    with_x.push(u16::from(b'x'));
    let edits = diff(&run, &with_x, true);
    let elapsed = started.elapsed();
    assert!(elapsed.as_secs_f64() <= 1.0, "{elapsed:?}");
    assert!(
        atoms.len() == 1 && !edits.is_empty(),
        "{} atoms, {} edits",
        atoms.len(),
        edits.len()
    );
}
