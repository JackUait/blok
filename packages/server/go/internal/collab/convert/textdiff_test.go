type textDiffCase struct {
	before, after jsjson.Str
	markup        bool
	atoms         []jsjson.Str
	elements      []int
	edits         []TextEdit
}

func loadTextDiffCases(t *testing.T) []textDiffCase {
	data, err := os.ReadFile(collabtest.Path(t, "text-diff/cases.json"))
	if err != nil {
		t.Fatal(err)
	}
	// jsjson keeps the lone surrogates encoding/json would replace.
	root, err := jsjson.Parse(data)
	if err != nil {
		t.Fatal(err)
	}
	get := func(value any, key string) any {
		v, _ := value.(*jsjson.Object).Get(jsjson.FromString(key))
		return v
	}
	var cases []textDiffCase
	for _, raw := range get(root, "cases").([]any) {
		c := textDiffCase{
			before: get(raw, "before").(jsjson.Str),
			after:  get(raw, "after").(jsjson.Str),
			markup: get(raw, "markup").(bool),
		}
		for _, atom := range get(raw, "atoms").([]any) {
			c.atoms = append(c.atoms, atom.(jsjson.Str))
		}
		for _, start := range get(raw, "elements").([]any) {
			c.elements = append(c.elements, int(start.(float64)))
		}
		for _, edit := range get(raw, "edits").([]any) {
			parts := edit.([]any)
			c.edits = append(c.edits, TextEdit{Index: int(parts[0].(float64)), Remove: int(parts[1].(float64)), Insert: parts[2].(jsjson.Str)})
		}
		cases = append(cases, c)
	}
	if len(cases) < 300 {
		t.Fatalf("only %d cases", len(cases))
	}
	return cases
}

func quote(s jsjson.Str) string {
	return fmt.Sprintf("%q", s.String())
}

func TestSplitsTextElementsLikeStringInfo(t *testing.T) {
	for i, c := range loadTextDiffCases(t) {
		if got := textElementStarts(c.before); !slices.Equal(got, c.elements) {
			t.Fatalf("case %d %s: %v, want %v", i, quote(c.before), got, c.elements)
		}
	}
}

func TestAtomizesLikeCSharp(t *testing.T) {
	for i, c := range loadTextDiffCases(t) {
		got := Atomize(c.before, c.markup)
		if !slices.EqualFunc(got, c.atoms, func(a, b jsjson.Str) bool { return slices.Equal(a, b) }) {
			t.Fatalf("case %d %s markup=%v:\n got %d atoms\nwant %d", i, quote(c.before), c.markup, len(got), len(c.atoms))
		}
	}
}

func TestDiffsLikeCSharp(t *testing.T) {
	for i, c := range loadTextDiffCases(t) {
		got := Diff(c.before, c.after, c.markup)
		if !slices.EqualFunc(got, c.edits, func(a, b TextEdit) bool {
			return a.Index == b.Index && a.Remove == b.Remove && slices.Equal(a.Insert, b.Insert)
		}) {
			t.Fatalf("case %d %s -> %s:\n got %v\nwant %v", i, quote(c.before), quote(c.after), got, c.edits)
		}
	}
}

// The Go table is generated from the C# capture; BLOK_WRITE_GO_TABLES=1 rewrites it.
func TestTheGraphemeTableIsTheCapture(t *testing.T) {
	data, err := os.ReadFile(collabtest.Path(t, "text-diff/grapheme-break.json"))
	if err != nil {
		t.Fatal(err)
	}
	var capture struct {
		Ranges [][3]any `json:"ranges"`
	}
	if err := json.Unmarshal(data, &capture); err != nil {
		t.Fatal(err)
	}
	var source bytes.Buffer
	source.WriteString("// Code generated by TestTheGraphemeTableIsTheCapture from\n")
	source.WriteString("// fixtures/text-diff/grapheme-break.json. DO NOT EDIT.\n\npackage convert\n\n")
	source.WriteString("// graphemeRanges is .NET's Grapheme_Cluster_Break table; code points not listed are Other.\n")
	source.WriteString("var graphemeRanges = []graphemeRange{\n")
	for _, r := range capture.Ranges {
		kind, ok := graphemeKinds[r[2].(string)]
		if !ok {
			t.Fatalf("unknown type %v", r[2])
		}
		fmt.Fprintf(&source, "\t{0x%X, 0x%X, %s},\n", int(r[0].(float64)), int(r[1].(float64)), kind)
	}
	source.WriteString("}\n")
	const path = "graphemes_table.go"
	if os.Getenv("BLOK_WRITE_GO_TABLES") == "1" {
		if err := os.WriteFile(path, source.Bytes(), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	committed, err := os.ReadFile(path)
	if err != nil || !bytes.Equal(committed, source.Bytes()) {
		t.Fatalf("%s is stale; rerun with BLOK_WRITE_GO_TABLES=1 (%v)", path, err)
	}
}

var graphemeKinds = map[string]string{
	"Control": "gbControl", "CR": "gbCR", "LF": "gbLF", "Extend": "gbExtend", "ZWJ": "gbZWJ",
	"Regional_Indicator": "gbRegionalIndicator", "Prepend": "gbPrepend", "SpacingMark": "gbSpacingMark",
	"L": "gbL", "V": "gbV", "T": "gbT", "LV": "gbLV", "LVT": "gbLVT", "Extended_Pictograph": "gbExtendedPictograph",
}
