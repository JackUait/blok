/** Writes the header of a one-item, one-client update and stops before the content. */
function writeItemHeader(encoder, { info = 0x28, parentName = 'm', client = CLIENT_A, structs = 1, clients = 1 } = {}) {
  encoding.writeVarUint(encoder, clients);
  encoding.writeVarUint(encoder, structs);
  encoding.writeVarUint(encoder, client);
  encoding.writeVarUint(encoder, 0);
  encoding.writeUint8(encoder, info);

  if (parentName !== null) {
    encoding.writeVarUint(encoder, 1);
    encoding.writeVarString(encoder, parentName);
  }
}

const assemble = (write) => {
  const encoder = encoding.createEncoder();

  write(encoder);

  return encoding.toUint8Array(encoder);
};

