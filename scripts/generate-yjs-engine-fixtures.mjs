// Generates the conformance fixtures the managed C# Yjs engine (Blok.Server.Yjs)
// is pinned to, under test/unit/server-conformance/fixtures/yjs-engine/
// (beside sync-frames.json; NOT under fixtures/collab/, which
// generate-collab-fixtures.mjs wipes wholesale).
//
//   node scripts/generate-yjs-engine-fixtures.mjs [--out <dir>]
//
// Every positive byte sequence is produced by the REAL yjs encoders over raw
// Y.Doc instances with pinned client ids — never through the Blok client store,
// whose nanoid row keys are not deterministic. negative.json is the one
// exception and says so in its own header.
//
// The JSON oracle is NEVER doc.toJSON(): a root created by integration is an
// untyped placeholder that serialises to nothing, JSON.stringify throws on a
// bigint and erases NaN/-0/Infinity/undefined, and Y.Text.toJSON() drops embeds
// and formats. scripts/yjs-engine-render.mjs is the only oracle; it emits the
// sentinels the C# side reproduces after canonicalisation.
//
// Byte determinism (which the collab fixtures do NOT have) rests on: no import
// of src/components/modules/yjs/* (nanoid lives there); grids built from raw
// Y.Map/Y.Array with literal __rowKeys; every doc.clientID pinned before the
// first write and asserted unchanged at the end (yjs regenerates it when a
// remote transaction advances the local clock); and manifest.json carrying the
// yjs/lib0 versions so a dependency bump goes red before the bytes drift.
//
// Refinements over the plan's illustrative layout, all additive:
//   * values everywhere use Locked Decision 10's sentinel vocabulary
//     ({"$num":..}, {"$bigint":..}, {"$u8":..}, {"$undefined":true}) instead of
//     the stringly form, because "-0" as a bare string is ambiguous against the
//     genuine strings the NUL cases carry, and one value decoder then serves
//     every file;
//   * ops carry an explicit "op" discriminator plus root/rootKind/path so a C#
//     reader needs no key-presence union;
//   * scenario steps carry "kind" and an "id", and a delayed or duplicated
//     delivery references the producing step by "updateOf" so the C# side can
//     substitute the engine's own bytes for an engineWrites step;
//   * negative cases carry "yjsAccepts", measured by running each through
//     Y.applyUpdate — trailing garbage, a twice-listed client and a v2 update
//     are accepted by yjs and must still be refused by ours.
