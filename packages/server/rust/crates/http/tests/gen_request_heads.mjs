// Writes request_heads_cases.rs from REQUEST_HEADS in
// http-host-contract.test.ts, so the Rust golden test sends the same bytes.
// Run from the repository root: node packages/server/rust/crates/http/tests/gen_request_heads.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const source = readFileSync('test/unit/server-conformance/http-host-contract.test.ts', 'utf8');
const start = source.indexOf('const CLOSE = ');
const end = source.indexOf("it('refuses request heads");
const block = source
  .slice(start, end)
  .replace('(headers: string): string =>', '(headers) =>')
  .replace('(count: number): string =>', '(count) =>')
  .replace('(...parts: Array<string | number[]>): Buffer =>', '(...parts) =>')
  .replace('const REQUEST_HEADS: Record<string, Buffer> =', 'const REQUEST_HEADS =');
const heads = new Function('Buffer', `${block}\nreturn REQUEST_HEADS;`)(Buffer);

const literal = (bytes) => {
  let out = 'b"';
  for (const b of bytes) {
    if (b === 0x22) out += '\\"';
    else if (b === 0x5c) out += '\\\\';
    else if (b === 0x0d) out += '\\r';
    else if (b === 0x0a) out += '\\n';
    else if (b === 0x09) out += '\\t';
    else if (b >= 0x20 && b < 0x7f) out += String.fromCharCode(b);
    else out += `\\x${b.toString(16).padStart(2, '0')}`;
  }
  return `${out}"`;
};

// Long runs of one byte are written as a repeat, to keep the file small.
const pieces = (bytes) => {
  const out = [];
  let i = 0;
  let plain = [];
  while (i < bytes.length) {
    let j = i;
    while (j < bytes.length && bytes[j] === bytes[i]) j++;
    if (j - i >= 64) {
      if (plain.length) out.push(`Piece::Bytes(${literal(plain)})`);
      plain = [];
      out.push(`Piece::Repeat(${bytes[i]}, ${j - i})`);
    } else {
      plain.push(...bytes.subarray(i, j));
    }
    i = j;
  }
  if (plain.length) out.push(`Piece::Bytes(${literal(plain)})`);
  return out.join(', ');
};

let rust = '// Generated by gen_request_heads.mjs from http-host-contract.test.ts; do not edit.\n\n';
rust += 'pub enum Piece {\n    Bytes(&\'static [u8]),\n    Repeat(u8, usize),\n}\n\n';
rust += '/// REQUEST_HEADS, in its order.\n';
rust += 'pub const REQUEST_HEADS: &[(&str, &[Piece])] = &[\n';
for (const [name, request] of Object.entries(heads)) {
  rust += `    (${JSON.stringify(name)}, &[${pieces(request)}]),\n`;
}
rust += '];\n\n';
rust += 'pub fn request_bytes(pieces: &[Piece]) -> Vec<u8> {\n';
rust += '    let mut out = Vec::new();\n';
rust += '    for piece in pieces {\n';
rust += '        match piece {\n';
rust += '            Piece::Bytes(bytes) => out.extend_from_slice(bytes),\n';
rust += '            Piece::Repeat(byte, count) => out.extend(std::iter::repeat_n(*byte, *count)),\n';
rust += '        }\n';
rust += '    }\n';
rust += '    out\n';
rust += '}\n';
writeFileSync('packages/server/rust/crates/http/tests/request_heads_cases.rs', rust);
console.log(`${Object.keys(heads).length} cases`);
