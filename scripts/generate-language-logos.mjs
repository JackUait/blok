#!/usr/bin/env node
/**
 * Generates `src/tools/code/language-logos.ts` from a PINNED Simple Icons
 * release: one SVG path and brand hex per language the code block lists.
 *
 * LICENSING IS THE FILTER. Simple Icons is CC0 as a project, but single icons
 * carry their own licenses. Blok is Apache-2.0, so:
 * - copyleft icons (any CC-BY-SA) are never vendored;
 * - permissive icons that require attribution (MIT) are vendored only when
 *   their notice is in NOTICE (see ATTRIBUTED below);
 * - an icon whose license text could not be verified (OpenJDK's BSD Duke) is
 *   left out.
 * The generator refuses to write if a picked icon's license changed.
 * Guarded by test/unit/tools/code/language-logos.test.ts.
 *
 * Run: `node scripts/generate-language-logos.mjs` (needs network).
 */
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const VERSION = '16.33.0';
const CDN = `https://cdn.jsdelivr.net/npm/simple-icons@${VERSION}`;
const OUT = join(resolve(dirname(fileURLToPath(import.meta.url)), '..'), 'src/tools/code/language-logos.ts');

/** Code-block language id → Simple Icons slug. */
const PICKS = {
  javascript: 'javascript',
  typescript: 'typescript',
  python: 'python',
  c: 'c',
  cpp: 'cplusplus',
  go: 'go',
  swift: 'swift',
  kotlin: 'kotlin',
  latex: 'latex',
  mermaid: 'mermaid',
  html: 'html5',
  css: 'css',
  json: 'json',
  yaml: 'yaml',
  markdown: 'markdown',
  bash: 'gnubash',
  dockerfile: 'docker',
  xml: 'xml',
  graphql: 'graphql',
  scala: 'scala',
  dart: 'dart',
  lua: 'lua',
};

/** Icons with a license entry that are allowed in, and why. Anything else with a license entry stops the run. */
const ATTRIBUTED = {
  javascript: 'MIT — notice for logo.js (Christopher Williams) is in NOTICE',
  gnubash: 'MIT — notice for official-bash-logo is in NOTICE',
  markdown: 'CC0-1.0',
};

/**
 * Square logos whose letters are holes: the holes are filled with the logo's
 * own second color, so JS reads black-on-yellow and TS white-on-blue as in
 * the real marks, not menu-background-on-color.
 */
const INNER = {
  javascript: '#000000',
  typescript: '#ffffff',
};

const fetchText = async (url) => {
  const response = await fetch(url);

  if (!response.ok) {
    throw new Error(`${url}: HTTP ${response.status}`);
  }

  return response.text();
};

const main = async () => {
  const data = JSON.parse(await fetchText(`${CDN}/data/simple-icons.json`));
  const bySlug = new Map(data.map((icon) => [icon.slug, icon]));
  const entries = [];

  for (const [id, slug] of Object.entries(PICKS)) {
    const icon = bySlug.get(slug);

    if (icon === undefined) {
      throw new Error(`simple-icons@${VERSION} has no "${slug}"`);
    }

    const license = icon.license?.type;

    if (license !== undefined && !(slug in ATTRIBUTED && ATTRIBUTED[slug].startsWith(license))) {
      throw new Error(`"${slug}" is ${license}; review it before vendoring (see ATTRIBUTED)`);
    }

    const svg = await fetchText(`${CDN}/icons/${slug}.svg`);
    const path = /<path d="([^"]+)"/.exec(svg)?.[1];

    if (path === undefined || !svg.includes('viewBox="0 0 24 24"')) {
      throw new Error(`"${slug}": unexpected SVG shape`);
    }

    entries.push({ id, slug, title: icon.title, hex: `#${icon.hex.toLowerCase()}`, license: license ?? 'none listed', path });
  }

  const body = entries
    .map(({ id, slug, title, hex, license, path }) => [
      `  /** ${title} (simple-icons "${slug}", license: ${license}) */`,
      `  ['${id}', {`,
      `    hex: '${hex}',`,
      ...(INNER[slug] ? [`    inner: '${INNER[slug]}',`] : []),
      `    path: '${path}',`,
      '  }],',
    ].join('\n'))
    .join('\n');

  writeFileSync(OUT, `/**
 * GENERATED by scripts/generate-language-logos.mjs from simple-icons@${VERSION}.
 * Do not edit by hand; re-run the script. Each entry names its source icon and
 * license. Copyleft icons are deliberately absent (see the script header);
 * attribution for the MIT icons is in NOTICE.
 */

export interface LanguageLogo {
  /** Brand color from Simple Icons. */
  hex: string;
  /** Fill for the letter holes of square logos, so they read as the real mark. */
  inner?: string;
  /** Path data on a 24×24 view box. */
  path: string;
}

/**
 * Built from entries, not an object literal: a \`css:\` key would make the
 * Tailwind class law read the CSS path data as class names.
 */
export const LANGUAGE_LOGOS: Readonly<Record<string, LanguageLogo>> = Object.fromEntries<LanguageLogo>([
${body}
]);
`);

  console.log(`wrote ${entries.length} logos to ${OUT}`);
};

await main();
