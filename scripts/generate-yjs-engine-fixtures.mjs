const b64 = (bytes) => Buffer.from(bytes).toString('base64');
const fromB64 = (text) => new Uint8Array(Buffer.from(text, 'base64'));

/**
 * Recursively key-sorted clone, so a hash of the JSON does not depend on key order.
 * @param {unknown} value
 * @returns {unknown}
 */
function canonicalize(value) {
  if (Array.isArray(value)) {
    return value.map(canonicalize);
  }

  if (value !== null && typeof value === 'object') {
    const out = {};

    for (const key of Object.keys(value).sort()) {
      out[key] = canonicalize(value[key]);
    }

    return out;
  }

  return value;
}

const jsonSha256 = (value) =>
  createHash('sha256').update(JSON.stringify(canonicalize(value)), 'utf8').digest('hex');

/**
 * Builds a live JS/yjs value from its fixture descriptor.
 * @param {unknown} desc
 * @returns {unknown}
 */
function buildValue(desc) {
  if (desc === null || typeof desc !== 'object') {
    return desc;
  }

  if (Array.isArray(desc)) {
    return desc.map(buildValue);
  }

  if ('$num' in desc) {
    const numbers = { '-0': -0, '-Infinity': Number.NEGATIVE_INFINITY, Infinity: Number.POSITIVE_INFINITY, NaN: Number.NaN };

    if (!(desc.$num in numbers)) {
      throw new TypeError(`unknown $num sentinel "${desc.$num}"`);
    }

    return numbers[desc.$num];
  }

  if ('$bigint' in desc) {
    return BigInt(desc.$bigint);
  }

  if ('$u8' in desc) {
    return fromB64(desc.$u8);
  }

  if ('$undefined' in desc) {
    return undefined;
  }

  if ('$ymap' in desc) {
    const map = new Y.Map();

    for (const [key, child] of Object.entries(desc.$ymap)) {
      map.set(key, buildValue(child));
    }

    return map;
  }

  if ('$yarray' in desc) {
    const array = new Y.Array();

    array.push(desc.$yarray.map(buildValue));

    return array;
  }

  if ('$ytext' in desc) {
    return new Y.Text(desc.$ytext);
  }

  if ('$yxmltext' in desc) {
    return new Y.XmlText(desc.$yxmltext);
  }

  if ('$yxmlelement' in desc) {
    const element = new Y.XmlElement(desc.$yxmlelement.nodeName);

    element.insert(0, desc.$yxmlelement.children.map(buildValue));

    return element;
  }

  if ('$yxmlfragment' in desc) {
    const fragment = new Y.XmlFragment();

    fragment.insert(0, desc.$yxmlfragment.map(buildValue));

    return fragment;
  }

  const out = {};

  for (const [key, child] of Object.entries(desc)) {
    out[key] = buildValue(child);
  }

  return out;
}

/**
 * @param {Y.Doc} doc
 * @param {Record<string, unknown>} op
 * @returns {void}
 */
function applyOp(doc, op) {
  const ctor = ROOT_CTORS[op.rootKind];

  if (ctor === undefined) {
    throw new TypeError(`unknown rootKind "${op.rootKind}"`);
  }

  let target = doc.get(op.root, ctor);

  for (const segment of op.path ?? []) {
    target = target.get(segment);
  }

  switch (op.op) {
    case 'map.set':
      target.set(op.key, buildValue(op.value));
      break;
    case 'map.delete':
      target.delete(op.key);
      break;
    case 'array.insert':
      target.insert(op.index, op.values.map(buildValue));
      break;
    case 'array.delete':
      target.delete(op.index, op.length);
      break;
    case 'text.insert':
      target.insert(op.index, op.text, op.attributes ?? undefined);
      break;
    case 'text.delete':
      target.delete(op.index, op.length);
      break;
    case 'text.format':
      target.format(op.index, op.length, op.attributes);
      break;
    case 'text.embed':
      target.insertEmbed(op.index, buildValue(op.embed), op.attributes ?? undefined);
      break;
    default:
      throw new TypeError(`unknown op "${op.op}"`);
  }
}

/** A set of pinned docs plus the recorder that captures one update per local op. */
class World {
  /**
   * @param {Array<[string, number]>} docs
   * @param {boolean} gc
   */
  constructor(docs, gc) {
    this.clientIds = new Map(docs);
    this.docs = new Map();

    for (const [name, clientId] of docs) {
      const doc = new Y.Doc({ gc });

      doc.clientID = clientId;
      this.docs.set(name, doc);
    }
  }

  /**
   * @param {string} name
   * @returns {Y.Doc}
   */
  doc(name) {
    const doc = this.docs.get(name);

    if (doc === undefined) {
      throw new Error(`no doc named "${name}"`);
    }

    return doc;
  }

  /**
   * Runs one op in its own transaction and returns the single update it emitted.
   * Every op the generator produces changes something, so zero updates is a bug.
   * @param {string} name
   * @param {Record<string, unknown>} op
   * @returns {Uint8Array}
   */
  record(name, op) {
    const doc = this.doc(name);
    const captured = [];
    const listener = (update, origin) => {
      if (origin === LOCAL_ORIGIN) {
        captured.push(update);
      }
    };

    doc.on('update', listener);
    doc.transact(() => applyOp(doc, op), LOCAL_ORIGIN);
    doc.off('update', listener);

    if (captured.length !== 1) {
      throw new Error(`op ${op.op} on "${name}" emitted ${captured.length} updates (expected 1)`);
    }

    return captured[0];
  }

  /**
   * @param {string} name
   * @param {Uint8Array} update
   * @returns {void}
   */
  deliver(name, update) {
    Y.applyUpdate(this.doc(name), update);
  }

  /**
   * @param {string} name
   * @param {Record<string, string>} roots
   * @returns {{ hasPending: boolean, json: Record<string, unknown>, sv: string }}
   */
  observe(name, roots) {
    const doc = this.doc(name);

    return {
      sv: b64(Y.encodeStateVector(doc)),
      hasPending: hasPending(doc),
      json: renderDoc(doc, roots),
    };
  }

  /** yjs regenerates clientID when a remote transaction advances the local clock. */
  assertClientIds() {
    for (const [name, clientId] of this.clientIds) {
      if (this.doc(name).clientID !== clientId) {
        throw new Error(`doc "${name}" regenerated its clientID (${clientId} -> ${this.doc(name).clientID})`);
      }
    }
  }

  destroy() {
    for (const doc of this.docs.values()) {
      doc.destroy();
    }
  }
}

