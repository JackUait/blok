const FUZZ_SCALARS = [
  0, 1, -1, 42, 2147483647, 2147483648, -2147483648, 0.5, 0.1, true, false, null,
  { $num: 'NaN' }, { $num: '-0' }, { $num: 'Infinity' }, { $num: '-Infinity' },
];
// Astral characters live in map/array values, never in fuzzed text: a random
// text.delete would split a surrogate pair and the halves are not portable.
const FUZZ_TEXT_STRINGS = ['a', 'bc', 'def', `n${NUL}l`, 'ключ'];

const pick = (rng, items) => items[Math.floor(rng() * items.length)];

/**
 * `allowBigint` is true only for a peer's map.set: real yjs itself refuses a
 * bigint in an array insert, and Locked Decision 2 keeps it off the engine's
 * write path entirely.
 * @param {() => number} rng
 * @param {boolean} allowBigint
 * @returns {unknown}
 */
function fuzzValue(rng, allowBigint) {
  const roll = rng();

  if (roll < 0.55) {
    return rng() < 0.5 ? pick(rng, FUZZ_SCALARS) : pick(rng, FUZZ_STRINGS);
  }

  if (roll < 0.7) {
    return { x: pick(rng, FUZZ_SCALARS), s: pick(rng, FUZZ_STRINGS), u: { $undefined: true } };
  }

  if (roll < 0.8) {
    return [pick(rng, FUZZ_SCALARS), null, pick(rng, FUZZ_STRINGS)];
  }

  if (roll < 0.88) {
    return { $u8: b64(Uint8Array.from([1, 2, Math.floor(rng() * 250)])) };
  }

  if (roll < 0.92 && allowBigint) {
    return { $bigint: String(Math.floor(rng() * 1e15) + 9007199254740990) };
  }

  if (roll < 0.96) {
    return { $ymap: { a: pick(rng, FUZZ_SCALARS), b: pick(rng, FUZZ_STRINGS) } };
  }

  return { $yarray: [pick(rng, FUZZ_STRINGS), pick(rng, FUZZ_SCALARS)] };
}

/**
 * Chooses one op that changes this doc — a delete only ever names live data, and
 * a text insert never draws the empty string, so `record` always sees an update.
 * @param {() => number} rng
 * @param {Y.Doc} doc
 * @param {boolean} peer true for A/B, false for the engine doc
 * @returns {Record<string, unknown>}
 */
function fuzzOp(rng, doc, peer) {
  const blocks = doc.get('blocks', Y.Map);
  const list = doc.get('list', Y.Array);
  const text = doc.get('content', Y.Text);
  const roll = rng();

  if (roll < 0.34) {
    const nested = [...blocks.keys()].filter((key) => blocks.get(key) instanceof Y.Map);

    if (rng() < 0.25 && nested.length > 0) {
      const path = [pick(rng, nested)];
      const inner = blocks.get(path[0]);
      const innerKeys = [...inner.keys()];

      if (rng() < 0.3 && innerKeys.length > 0) {
        return { op: 'map.delete', root: 'blocks', rootKind: 'map', path, key: pick(rng, innerKeys) };
      }

      return { op: 'map.set', root: 'blocks', rootKind: 'map', path, key: pick(rng, FUZZ_KEYS), value: fuzzValue(rng, peer) };
    }

    const keys = [...blocks.keys()];

    if (rng() < 0.25 && keys.length > 0) {
      return { op: 'map.delete', root: 'blocks', rootKind: 'map', path: [], key: pick(rng, keys) };
    }

    return { op: 'map.set', root: 'blocks', rootKind: 'map', path: [], key: pick(rng, FUZZ_KEYS), value: fuzzValue(rng, peer) };
  }

  if (roll < 0.67) {
    if (rng() < 0.3 && list.length > 0) {
      const index = Math.floor(rng() * list.length);

      return { op: 'array.delete', root: 'list', rootKind: 'array', path: [], index, length: 1 + Math.floor(rng() * Math.min(3, list.length - index)) };
    }

    const count = 1 + Math.floor(rng() * 3);

    return {
      op: 'array.insert',
      root: 'list',
      rootKind: 'array',
      path: [],
      index: Math.floor(rng() * (list.length + 1)),
      values: Array.from({ length: count }, () => fuzzValue(rng, false)),
    };
  }

  if (rng() < 0.3 && text.length > 0) {
    const index = Math.floor(rng() * text.length);

    return { op: 'text.delete', root: 'content', rootKind: 'text', path: [], index, length: 1 + Math.floor(rng() * Math.min(3, text.length - index)) };
  }

  return { op: 'text.insert', root: 'content', rootKind: 'text', path: [], index: Math.floor(rng() * (text.length + 1)), text: pick(rng, FUZZ_TEXT_STRINGS) };
}

// Repeated verbatim in all 50 seed files, so it stays terse; the reasoning
// behind it lives once in manifest.json.
const FUZZ_SCHEDULE = {
  prng: 'mulberry32(seed)',
  ops: OPS_PER_SEED,
  actors: 'A and B are peers, C is the engine and performs ~20% of the ops; only C-touching steps are recorded',
  opMix: '~34% map (root or one level down), ~33% array, ~33% text; ~25-30% of each deletes live data; no text formatting',
  values: 'scalars incl. -0/NaN/+-Infinity and the 2^31 edges, NUL-bearing and Cyrillic strings, astral (map and array values only), objects, arrays, an undefined member, Uint8Array, bigint (peer map.set only), nested Y.Map/Y.Array',
  delivery: '~60% of peer updates reach C at once, the rest are queued and flushed at a later PRNG-chosen step (gaps park pending structs); ~12% are delivered twice; the queue drains at the end, after which C holds no pending structs and renders what both peers render',
};

/**
 * @param {number} seed
 * @returns {Record<string, unknown>}
 */
function runFuzzSeed(seed) {
  const rng = mulberry32(seed);
  const world = new World(THREE_DOCS, true);
  const engine = 'C';
  const peers = ['A', 'B'];
  const steps = [];
  const queued = [];
  let counter = 0;

  const expectEngine = (full) => {
    const observed = world.observe(engine, FUZZ_ROOTS);
    const expect = { sv: observed.sv, hasPending: observed.hasPending, jsonSha256: jsonSha256(observed.json) };

    if (full) {
      expect.json = observed.json;
    }

    steps[steps.length - 1].expect = expect;
  };

  const drain = (entry) => {
    world.deliver(engine, entry.update);
    steps.push({ kind: 'deliver', id: `q${steps.length}`, update: entry.bytes });
    expectEngine(false);
  };

  for (let index = 0; index < OPS_PER_SEED; index += 1) {
    const engineTurn = rng() < 0.2;
    const actor = engineTurn ? engine : pick(rng, peers);
    const op = fuzzOp(rng, world.doc(actor), !engineTurn);
    const update = world.record(actor, op);

    counter += 1;

    const id = `s${counter}`;

    // Peer-to-peer traffic keeps the peers realistic but is never recorded.
    for (const peer of peers) {
      if (peer !== actor) {
        world.deliver(peer, update);
      }
    }

    if (engineTurn) {
      steps.push({ kind: 'engineWrites', id, doc: engine, op, update: b64(update) });
      expectEngine(false);
    } else if (rng() < 0.6) {
      world.deliver(engine, update);
      steps.push({ kind: 'deliver', id, update: b64(update) });
      expectEngine(false);
    } else {
      queued.push({ id, update, bytes: b64(update) });
    }

    if (rng() < 0.12 && steps.length > 0) {
      const source = steps.filter((step) => step.update !== undefined);

      if (source.length > 0) {
        const chosen = source[Math.floor(rng() * source.length)];

        world.deliver(engine, fromB64(chosen.update));
        steps.push({ kind: 'deliver', id: `dup${steps.length}`, updateOf: chosen.id });
        expectEngine(false);
      }
    }

    while (queued.length > 0 && rng() < 0.35) {
      drain(queued.splice(Math.floor(rng() * queued.length), 1)[0]);
    }
  }

  while (queued.length > 0) {
    drain(queued.splice(Math.floor(rng() * queued.length), 1)[0]);
  }

  // Peers still owe each other the engine's own writes; deliver them so the
  // convergence self-check below is meaningful.
  for (const step of steps) {
    if (step.kind === 'engineWrites') {
      for (const peer of peers) {
        world.deliver(peer, fromB64(step.update));
      }
    }
  }

  expectEngine(true);

  const engineJson = world.observe(engine, FUZZ_ROOTS);

  if (engineJson.hasPending) {
    throw new Error(`seed ${seed}: the engine doc still holds pending structs after the queue drained`);
  }

  for (const peer of peers) {
    const peerJson = world.observe(peer, FUZZ_ROOTS);

    if (jsonSha256(peerJson.json) !== jsonSha256(engineJson.json)) {
      throw new Error(`seed ${seed}: doc "${peer}" did not converge with the engine doc`);
    }
  }

  world.assertClientIds();

  const clientIds = Object.fromEntries(world.clientIds);

  world.destroy();

  return {
    $comment: DO_NOT_EDIT,
    $description:
      'A seeded delivery schedule replayed against ONE engine doc pinned to docs[engine]. Ops use ' +
      'the grammar scenarios.json documents. Steps differ from a scenario\'s in two ways, both to ' +
      'keep 50 seeds inside the fixture budget (manifest.json -> fuzz explains the arithmetic): a ' +
      '"deliver" step always targets the engine doc, so it carries no `to` and holds either ' +
      '`update` (bytes) or `updateOf` (re-delivery of the step with that id — substitute the ' +
      'engine\'s own bytes when that step was an engineWrites); and the oracle is an `expect` FIELD ' +
      'on every step, describing the engine doc AFTER that step, rather than a separate "expect" ' +
      'step. Only the last step carries the full `json` beside its `jsonSha256` (canonical JSON = ' +
      'keys sorted recursively, JSON.stringify with no spaces).',
    seed,
    schedule: FUZZ_SCHEDULE,
    gc: true,
    roots: FUZZ_ROOTS,
    engine,
    docs: clientIds,
    steps,
  };
}

