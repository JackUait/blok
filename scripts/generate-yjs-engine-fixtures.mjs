/**
 * @param {import('yjs').AbstractType<unknown>} type
 * @returns {number}
 */
function typeRefOf(type) {
  // YXmlText extends YText, YXmlElement extends YXmlFragment and YXmlHook
  // extends YMap, so the most specific class has to be tested first.
  for (const [ctor, ref] of TYPE_REFS) {
    if (type instanceof ctor) {
      return ref;
    }
  }

  throw new TypeError(`unknown shared type ${type.constructor.name}`);
}

const renderId = (id) => (id === null || id === undefined ? null : { client: id.client, clock: id.clock });

/**
 * A root parent stays a bare string on the wire; a nested parent is an ID; an
 * item that carries an origin writes neither.
 * @param {unknown} parent
 * @returns {unknown}
 */
function renderParent(parent) {
  if (parent === null || parent === undefined) {
    return null;
  }

  if (typeof parent === 'string') {
    return { root: parent };
  }

  return { item: renderId(parent) };
}

/**
 * @param {unknown} content
 * @returns {Record<string, unknown>}
 */
function renderContent(content) {
  const ref = content.getRef();

  switch (ref) {
    case 1:
      return { ref, len: content.len };
    case 2:
      return { ref, arr: content.arr.map(renderValue) };
    case 3:
      return { ref, bytes: b64(content.content) };
    case 4:
      return { ref, str: content.str };
    case 5:
      return { ref, embed: renderValue(content.embed) };
    case 6:
      return { ref, key: content.key, value: renderValue(content.value) };
    case 7: {
      const typeRef = typeRefOf(content.type);
      const rendered = { ref, typeRef };

      if (typeRef === 3) {
        rendered.nodeName = content.type.nodeName;
      }

      if (typeRef === 5) {
        rendered.hookName = content.type.hookName;
      }

      return rendered;
    }
    case 8:
      return { ref, arr: content.arr.map(renderValue) };
    case 9:
      return { ref, guid: content.doc.guid, opts: content.opts };
    default:
      throw new TypeError(`unknown content ref ${ref}`);
  }
}

/**
 * @param {unknown} struct
 * @returns {Record<string, unknown>}
 */
function renderStruct(struct) {
  const kind = struct.constructor.name;
  const head = { kind: kind.toLowerCase(), client: struct.id.client, clock: struct.id.clock, length: struct.length };

  if (kind === 'GC' || kind === 'Skip') {
    return head;
  }

  if (kind !== 'Item') {
    throw new TypeError(`unknown struct class ${kind}`);
  }

  return {
    ...head,
    origin: renderId(struct.origin),
    rightOrigin: renderId(struct.rightOrigin),
    parent: renderParent(struct.parent),
    parentSub: struct.parentSub ?? null,
    content: renderContent(struct.content),
  };
}

/**
 * @param {Uint8Array} update
 * @returns {Record<string, unknown>}
 */
function renderDecodedUpdate(update) {
  const decoded = Y.decodeUpdate(update);
  const deleteSet = {};

  for (const [client, ranges] of [...decoded.ds.clients.entries()].sort((a, b) => a[0] - b[0])) {
    deleteSet[client] = ranges.map((range) => [range.clock, range.len]);
  }

  return { structs: decoded.structs.map(renderStruct), deleteSet };
}

